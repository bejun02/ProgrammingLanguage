# 설비 개수 (고정)
MACHINE_COUNTS = {"A": 5, "B": 8, "C": 6, "D": 5, "E": 5}
AMR_COUNT = 5

def run_simulation(machine_positions, name=""):
    """시뮬레이션 실행 및 Profit 반환"""
    sim_core.reset_sim()
    
    cfg = sim_core.FactoryConfig(
        sim_time=86400,  # 1일로 축소 (빠른 테스트)
        seed=20,
        feed_sequence=("ProdA", "ProdB"),
        amr_count=AMR_COUNT,
        machine_counts=MACHINE_COUNTS,
        machine_positions=machine_positions
    )
    sim_core.simulate(cfg)
    
    # Profit 계산
    parameter = [4, 9, 8, 8, 5.5]
    t = sum(MACHINE_COUNTS[k] * parameter[i] for i, k in enumerate(MACHINE_COUNTS))
    
    a_count = len(global_variable.STOCKERS["STK-01"].list_jobs_A())
    b_count = len(global_variable.STOCKERS["STK-01"].list_jobs_B())
    feed_total = global_variable.FEED_COUNT_A + global_variable.FEED_COUNT_B
    
    p = 100 * min(a_count, b_count) - 5 * feed_total
    profit_val = p / (t + 0.011 * AMR_COUNT) * 100000
    
    return {
        "name": name,
        "profit": profit_val,
        "a_count": a_count,
        "b_count": b_count,
        "feed_total": feed_total,
        "pair": min(a_count, b_count)
    }


